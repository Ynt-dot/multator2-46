import { describe, it, expect } from 'vitest'
import { getRankByLikes } from '../../types'

// Пороги из RANKS:
// 0→1, 10→2, 50→3, 150→4, 500→5, 1000→6, 2500→7, 5000→8, 10000→9, 25000→10

// ---------------------------------------------------------------------------
// Нормальный ввод — попадание точно в порог
// ---------------------------------------------------------------------------
describe('Нормальный ввод — точные пороговые значения', () => {
  it('0 лайков — ранг 1 (Неизвестный)', () => {
    expect(getRankByLikes(0)).toBe(1)
  })

  it('10 лайков — ранг 2 (Новичок)', () => {
    expect(getRankByLikes(10)).toBe(2)
  })

  it('50 лайков — ранг 3 (Узнаваемый)', () => {
    expect(getRankByLikes(50)).toBe(3)
  })

  it('150 лайков — ранг 4 (Известный)', () => {
    expect(getRankByLikes(150)).toBe(4)
  })

  it('500 лайков — ранг 5 (Прославленный)', () => {
    expect(getRankByLikes(500)).toBe(5)
  })

  it('1000 лайков — ранг 6 (Выдающийся)', () => {
    expect(getRankByLikes(1000)).toBe(6)
  })

  it('2500 лайков — ранг 7 (Знаменитый)', () => {
    expect(getRankByLikes(2500)).toBe(7)
  })

  it('5000 лайков — ранг 8 (Величайший)', () => {
    expect(getRankByLikes(5000)).toBe(8)
  })

  it('10000 лайков — ранг 9 (Бессмертный)', () => {
    expect(getRankByLikes(10000)).toBe(9)
  })

  it('25000 лайков — ранг 10 (Легенда)', () => {
    expect(getRankByLikes(25000)).toBe(10)
  })
})

// ---------------------------------------------------------------------------
// Нормальный ввод — значения между порогами
// ---------------------------------------------------------------------------
describe('Нормальный ввод — значения между порогами', () => {
  it('9 лайков — ещё ранг 1, не 2', () => {
    expect(getRankByLikes(9)).toBe(1)
  })

  it('11 лайков — уже ранг 2, не 3', () => {
    expect(getRankByLikes(11)).toBe(2)
  })

  it('49 лайков — ещё ранг 2', () => {
    expect(getRankByLikes(49)).toBe(2)
  })

  it('149 лайков — ещё ранг 3', () => {
    expect(getRankByLikes(149)).toBe(3)
  })

  it('24999 лайков — ещё ранг 9, не 10', () => {
    expect(getRankByLikes(24999)).toBe(9)
  })
})

// ---------------------------------------------------------------------------
// Граничные значения
// ---------------------------------------------------------------------------
describe('Граничные значения', () => {
  it('ровно 0 лайков — минимальный ранг 1', () => {
    expect(getRankByLikes(0)).toBe(1)
  })

  it('очень большое число (Number.MAX_SAFE_INTEGER) — максимальный ранг 10', () => {
    expect(getRankByLikes(Number.MAX_SAFE_INTEGER)).toBe(10)
  })

  it('Infinity — максимальный ранг 10', () => {
    expect(getRankByLikes(Infinity)).toBe(10)
  })

  it('null — возвращает ранг 1 (null приводится к 0)', () => {
    expect(getRankByLikes(null as unknown as number)).toBe(1)
  })

  it('пустая строка — возвращает ранг 1 (пустая строка приводится к 0)', () => {
    expect(getRankByLikes('' as unknown as number)).toBe(1)
  })
})

// ---------------------------------------------------------------------------
// Ошибочный ввод
// ---------------------------------------------------------------------------
describe('Ошибочный ввод', () => {
  it('отрицательное число -1 — возвращает ранг 1', () => {
    expect(getRankByLikes(-1)).toBe(1)
  })

  it('отрицательное число -9999 — возвращает ранг 1', () => {
    expect(getRankByLikes(-9999)).toBe(1)
  })

  it('-Infinity — возвращает ранг 1', () => {
    expect(getRankByLikes(-Infinity)).toBe(1)
  })

  it('NaN — возвращает ранг 1 (NaN >= n всегда false)', () => {
    expect(getRankByLikes(NaN)).toBe(1)
  })

  it('undefined — возвращает ранг 1 (undefined >= n всегда false)', () => {
    expect(getRankByLikes(undefined as unknown as number)).toBe(1)
  })

  it('строка "abc" — возвращает ранг 1', () => {
    expect(getRankByLikes('abc' as unknown as number)).toBe(1)
  })

  it('строка "10" — возвращает ранг 2 (строка приводится к числу 10)', () => {
    expect(getRankByLikes('10' as unknown as number)).toBe(2)
  })
})

// ---------------------------------------------------------------------------
// Edge cases
// ---------------------------------------------------------------------------
describe('Edge cases', () => {
  it('ровно на 1 меньше максимального порога (24999) — ранг 9, а не 10', () => {
    expect(getRankByLikes(24999)).toBe(9)
  })

  it('ровно на 1 больше максимального порога (25001) — ранг 10', () => {
    expect(getRankByLikes(25001)).toBe(10)
  })

  it('ровно на 1 меньше второго порога (9) — ранг 1, а не 2', () => {
    expect(getRankByLikes(9)).toBe(1)
  })

  it('дробное число 10.5 — ранг 2 (дробь >= 10)', () => {
    expect(getRankByLikes(10.5)).toBe(2)
  })

  it('дробное число 9.9999 — ранг 1 (меньше 10)', () => {
    expect(getRankByLikes(9.9999)).toBe(1)
  })

  it('функция детерминирована: одинаковый вход всегда даёт одинаковый выход', () => {
    expect(getRankByLikes(500)).toBe(getRankByLikes(500))
  })

  it('значение ровно на границе последнего ранга не превышает 10', () => {
    expect(getRankByLikes(25000)).toBeLessThanOrEqual(10)
  })
})
